    /** null / "" = 跟随系统的默认配色（内置 Light/Dark）。 */
    fun byId(id: String?): Preset? = all.firstOrNull { it.id == id }

    /**
     * 解析 dream-skin 用到的 CSS 颜色： #rgb / #rrggbb / #rrggbbaa / rgb() / rgba()。
     * 解析不了返回 null（该 token 落回基础配色）。
     */
    fun parseCssColor(css: String?): androidx.compose.ui.graphics.Color? {
        val text = css?.trim() ?: return null
        if (text.startsWith("#")) {
            val hex = text.substring(1)
            return when (hex.length) {
                3 -> androidx.compose.ui.graphics.Color(
                    hex[0].digit(16) * 17, hex[1].digit(16) * 17, hex[2].digit(16) * 17, 255,
                )
                6 -> androidx.compose.ui.graphics.Color(
                    hex.substring(0, 2).toInt(16), hex.substring(2, 4).toInt(16), hex.substring(4, 6).toInt(16), 255,
                )
                8 -> androidx.compose.ui.graphics.Color(
                    hex.substring(0, 2).toInt(16), hex.substring(2, 4).toInt(16), hex.substring(4, 6).toInt(16), hex.substring(6, 8).toInt(16),
                )
                else -> null
            }
        }
        val open = text.indexOf('(')
        if (open < 0 || !text.endsWith(")")) return null
        val fn = text.substring(0, open).trim().lowercase()
        if (fn != "rgb" && fn != "rgba") return null
        val parts = text.substring(open + 1, text.length - 1).split(',').map { it.trim() }
        if (parts.size < 3) return null
        val r = parts[0].toIntOrNull() ?: return null
        val g = parts[1].toIntOrNull() ?: return null
        val b = parts[2].toIntOrNull() ?: return null
        val a = if (parts.size > 3) ((parts[3].toFloatOrNull() ?: return null) * 255f).toInt().coerceIn(0, 255) else 255
        return androidx.compose.ui.graphics.Color(r, g, b, a)
    }
